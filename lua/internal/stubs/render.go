// luaWorldFuncs are the functions of the Lua `world` table (the lua module,
// doc/guide/world-api.md) that the stub declares. A test compares this list
// with the doc and the implementation, so the stub cannot silently drift.
var luaWorldFuncs = []string{"despawn", "dump", "get", "remove", "set", "spawn"}

// renderLua writes the document as one LuaLS meta file: classes for the
// components and objects, an alias of the object keys, and the `world` API and
// script contract of the lua module typed against them.
func renderLua(doc *document) string {
	w := &luaWriter{}
	w.line("---@meta")
	w.line("-- " + doc.Title + ": LuaLS definitions generated by ecslua stubs from the GOD files.")
	w.line("-- Do not edit; regenerate with `go tool ecslua stubs`.")

	objects := doc.objects()

	w.blank()
	w.line("--- An object key, \"group:class\", of a registered Game Object.")
	w.line("---@alias GodObject")
	for _, o := range objects {
		w.line("---| " + luaString(o.key()) + luaAliasDoc(o.Doc))
	}

	w.blank()
	w.line("--- An opaque entity handle. It may be stored and compared with ==.")
	w.line("---@class Entity")

	w.blank()
	w.line("--- The table a script returns. T is the object class `update` receives.")
	w.line("---@class GodScript<T>")
	w.line("---@field object GodObject The Game Object the script runs for.")
	w.line("---@field init? fun() Called once when the script is loaded.")
	w.line("---@field update fun(dt: number, e: Entity, obj: T) Called once per matching entity per tick.")

	for _, c := range doc.Components {
		w.blank()
		w.component(c)
	}
	for _, o := range objects {
		w.blank()
		w.object(o)
	}

	w.blank()
	w.world(objects)
	return w.b.String()
}

// objects returns every object of the document, sorted by group and class.
func (d *document) objects() []*object {
	var all []*object
	for _, g := range d.Groups {
		all = append(all, g.Objects...)
	}
	return all
}

type luaWriter struct {
	b strings.Builder
}

func (w *luaWriter) line(s string) { w.b.WriteString(s + "\n") }
func (w *luaWriter) blank()        { w.b.WriteString("\n") }

// docLines writes text as `---` description lines (paragraphs stay separate).
func (w *luaWriter) docLines(text string) {
	if text == "" {
		return
	}
	for l := range strings.SplitSeq(strings.TrimSpace(text), "\n") {
		w.line(strings.TrimRight("--- "+l, " "))
	}
}

// luaIdent sanitizes s for use inside a LuaLS class name.
func luaIdent(s string) string {
	return strings.Map(func(r rune) rune {
		if r == '_' || unicode.IsLetter(r) || unicode.IsDigit(r) {
			return r
		}
		return '_'
	}, s)
}

// componentClass is the LuaLS name of a component type, "god.<group>.<Name>":
// unique, because component keys are.
func componentClass(c *component) string {
	return "god." + luaIdent(c.Group) + "." + luaIdent(c.Name)
}

// componentNames are the names a script may use for component c of o: its
// key, and its bare name when no other component of o has that name (see
// doc/guide/README.md).
func componentNames(o *object, c objectComponent) []string {
	names := []string{c.Comp.Key}
	for _, other := range o.Components {
		if other.Comp != c.Comp && other.Comp.Name == c.Comp.Name {
			return names
		}
	}
	return append(names, c.Comp.Name)
}

// objectClass is the LuaLS name of a Game Object: "group.Class".
func objectClass(o *object) string {
	return luaIdent(o.Group) + "." + luaIdent(o.Class)
}

// collapse joins the lines of doc into one, for single-line descriptions.
func collapse(doc string) string {
	return strings.Join(strings.Fields(doc), " ")
}

// luaAliasDoc is the trailing "# first paragraph" of an alias member.
func luaAliasDoc(doc string) string {
	first, _, _ := strings.Cut(strings.TrimSpace(doc), "\n\n")
	if first = collapse(first); first != "" {
		return " # " + first
	}
	return ""
}

// luaString quotes s as a Lua string literal for alias members and parameters.
func luaString(s string) string {
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(s) + `"`
}

// isObjectClass reports whether s becomes a LuaLS class (a struct) rather than
// an alias or a plain type.
func isObjectClass(s *god.TypeSchema) bool {
	return s != nil && s.Type == "object" && s.AdditionalProperties == nil && s.GoType == "" && !s.PreserveUnknownFields
}

// luaNested is a class found while mapping a field type; it is written after
// the class that contains it.
type luaNested struct {
	name   string
	schema *god.TypeSchema
}

// luaType maps a schema to a LuaLS type expression. Nested structs become
// classes named after name (the path of property names); they are appended to
// nested.
func luaType(s *god.TypeSchema, name string, nested *[]luaNested) string {
	var t string
	switch {
	case s == nil || s.PreserveUnknownFields || s.GoType != "":
		return "any"
	case s.Format == god.FormatEntity:
		t = "Entity" // ecs.Entity fields read as entity handles in Lua
	case s.Type == "string":
		t = "string"
	case s.Type == "integer":
		t = "integer"
	case s.Type == "number":
		t = "number"
	case s.Type == "boolean":
		t = "boolean"
	case s.Type == "array":
		item := luaType(s.Items, name, nested)
		if s.Items != nil && s.Items.Nullable {
			item = "(" + item + ")"
		}
		t = item + "[]"
	case s.Type == "object" && s.AdditionalProperties != nil:
		t = "table<string, " + luaType(s.AdditionalProperties, name, nested) + ">"
	case s.Type == "object" && len(s.Properties) > 0:
		*nested = append(*nested, luaNested{name, s})
		t = name
	default:
		t = "table"
	}
	if s.Nullable {
		t += "?"
	}
	return t
}

// fieldName is the name of a LuaLS field; names that are not identifiers use
// the bracket form.
func fieldName(name string) string {
	ok := name != ""
	for i, r := range name {
		if r != '_' && !unicode.IsLetter(r) && (i == 0 || !unicode.IsDigit(r)) {
			ok = false
		}
	}
	if ok {
		return name
	}
	return "[" + luaString(name) + "]"
}

// luaField is a "---@field" line without description. An optional field is
// "name?" for an identifier; the bracket form (["gfx:Transform"]) has no "?"
// suffix in LuaLS, so its type is made nullable instead.
func luaField(name string, optional bool, typ string) string {
	f := fieldName(name)
	switch {
	case optional && strings.HasPrefix(f, "["):
		typ += "?"
	case optional:
		f += "?"
	}
	return "---@field " + f + " " + typ
}

// class writes one LuaLS class for the struct schema s, then the classes nested
// inside it.
func (w *luaWriter) class(name, doc string, s *god.TypeSchema) {
	w.docLines(doc)
	w.line("---@class " + name)

	var nested []luaNested
	props := make([]string, 0, len(s.Properties))
	for p := range s.Properties {
		props = append(props, p)
	}
	slices.Sort(props)
	for _, p := range props {
		ps := s.Properties[p]
		opt := ""
		if !slices.Contains(s.Required, p) {
			opt = "?"
		}
		typ := luaType(ps, name+"."+luaIdent(p), &nested)
		if opt != "" {
			typ = strings.TrimSuffix(typ, "?") // "name?" already means "may be nil"
		}
		line := luaField(p, opt != "", typ)
		if d := collapse(ps.Description); d != "" {
			line += " " + d
		}
		w.line(line)
	}
	for _, n := range nested {
		w.blank()
		w.class(n.name, n.schema.Description, n.schema)
	}
}

// component writes the class (or alias, for a component that is not a struct)
// of one component type.
func (w *luaWriter) component(c *component) {
	name := componentClass(c)
	schema := c.def.Schema
	if isObjectClass(schema) {
		w.class(name, c.Doc, schema)
		return
	}
	var nested []luaNested
	w.docLines(c.Doc)
	w.line("---@alias " + name + " " + luaType(schema, name, &nested))
	for _, n := range nested {
		w.blank()
		w.class(n.name, n.schema.Description, n.schema)
	}
}

// object writes the class of a Game Object: one field per name of each
// component (its key, and its bare name when unique), optional components
// marked with "?".
func (w *luaWriter) object(o *object) {
	w.docLines(o.Doc)
	w.line("---@class " + objectClass(o))
	for _, c := range o.Components {
		for _, name := range componentNames(o, c) {
			w.objectField(name, c)
		}
	}
}

// objectField writes one field of an object class.
func (w *luaWriter) objectField(name string, c objectComponent) {
	line := luaField(name, c.Optional, componentClass(c.Comp))
	var notes []string
	if d := collapse(c.Doc); d != "" {
		notes = append(notes, d)
	}
	if c.Readonly {
		notes = append(notes, "(readonly)")
	}
	if c.Embedded() {
		notes = append(notes, "(embedded via "+strings.Join(c.Via, ".")+")")
	}
	if len(notes) > 0 {
		line += " " + strings.Join(notes, " ")
	}
	w.line(line)
}

// world writes the `world` table of the lua module with one overload per Game
// Object, so object keys complete and results are typed.
func (w *luaWriter) world(objects []*object) {
	overloads := func(f func(o *object) []string) {
		for _, o := range objects {
			for _, s := range f(o) {
				w.line("---@overload " + s)
			}
		}
	}

	w.line("--- The Game Object API of the lua module. Structural changes are queued and applied after the stage.")
	w.line("world = {}")

	w.blank()
	w.line("--- Queues the despawn of an entity.")
	w.line("---@param e Entity")
	w.line("function world.despawn(e) end")

	w.blank()
	w.line("--- Validates the components now and queues the creation of a new entity.")
	w.line("---@param object GodObject")
	w.line("---@param components table")
	overloads(func(o *object) []string {
		return []string{"fun(object: " + luaString(o.key()) + ", components: " + objectClass(o) + ")"}
	})
	w.line("function world.spawn(object, components) end")

	w.blank()
	w.line("--- Validates the value now and queues adding or replacing one component.")
	w.line("---@param e Entity")
	w.line("---@param object GodObject")
	w.line("---@param component string")
	w.line("---@param value table")
	overloads(func(o *object) []string {
		var out []string
		for _, c := range o.Components {
			for _, name := range componentNames(o, c) {
				out = append(out, "fun(e: Entity, object: "+luaString(o.key())+", component: "+luaString(name)+", value: "+componentClass(c.Comp)+")")
			}
		}
		return out
	})
	w.line("function world.set(e, object, component, value) end")

	w.blank()
	w.line("--- Queues the removal of an optional component.")
	w.line("---@param e Entity")
	w.line("---@param object GodObject")
	w.line("---@param component string")
	overloads(func(o *object) []string {
		var out []string
		for _, c := range o.Components {
			if !c.Optional {
				continue
			}
			for _, name := range componentNames(o, c) {
				out = append(out, "fun(e: Entity, object: "+luaString(o.key())+", component: "+luaString(name)+")")
			}
		}
		return out
	})
	w.line("function world.remove(e, object, component) end")

	w.blank()
	w.line("--- An object for the entity, or nil if it lacks a required component. Valid for the current call only.")
	w.line("---@param e Entity")
	w.line("---@param object GodObject")
	w.line("---@return table?")
	overloads(func(o *object) []string {
		return []string{"fun(e: Entity, object: " + luaString(o.key()) + "): " + objectClass(o) + "?"}
	})
	w.line("function world.get(e, object) end")

	w.blank()
	w.line("--- The components of the entity as a Lua table (a copy).")
	w.line("---@param e Entity")
	w.line("---@param object GodObject")
	w.line("---@return table")
	overloads(func(o *object) []string {
		return []string{"fun(e: Entity, object: " + luaString(o.key()) + "): " + objectClass(o)}
	})
	w.line("function world.dump(e, object) end")
}

// Render reads the GOD files named by inputs (files, directories and "..."
// patterns) and returns one LuaLS meta file for them, titled title. Equal
// definitions in several files collapse into one, different ones under the same
// key are an error; all problems are reported together.
func Render(title string, inputs []string) (string, error) {
	files, err := collect(inputs)
	if err != nil {
		return "", err
	}
	doc, err := loadDocument(title, files)
	if err != nil {
		return "", err
	}
	return renderLua(doc), nil
}
